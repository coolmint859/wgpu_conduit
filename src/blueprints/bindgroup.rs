use std::{hash::{DefaultHasher, Hash, Hasher}, num::NonZero};

use async_store::HoldPolicy;
use uuid::Uuid;

use crate::{TextureHandle, context::*};

pub(crate) enum ResolvedTarget {
    Buffer(wgpu::Buffer),
    Texture(TextureHandle),
    Sampler(wgpu::Sampler),
}

impl ResolvedTarget {
    pub fn to_wgpu_binding(&self) -> wgpu::BindingResource<'_> {
        match self {
            ResolvedTarget::Buffer(buf) => buf.as_entire_binding(),
            ResolvedTarget::Texture(tex) => wgpu::BindingResource::TextureView(&tex.view),
            ResolvedTarget::Sampler(samp) => wgpu::BindingResource::Sampler(samp)
        }
    }
}

/// The target ID for a bind group entry
#[derive(Clone, Debug)]
pub enum BindingTarget {
    Buffer(BufferId),
    Texture(TextureId),
    Sampler(SamplerId),
}

impl BindingTarget {
    /// Resolves the target id into a `ResolvedTarget`, if available. Marks the resource as accessed.
    pub(crate) fn resolve(&self, resources: &GpuResources) -> Option<ResolvedTarget> {
        match &self {
            BindingTarget::Buffer(id) => {
                return resources.buffers.get(id).cloned().map(ResolvedTarget::Buffer);
            }
            BindingTarget::Texture(id) => {
                return resources.textures.get(id).cloned().map(ResolvedTarget::Texture)
            }
            BindingTarget::Sampler(id) => {
                return resources.samplers.get(id).cloned().map(ResolvedTarget::Sampler);
            }
        }
    }

    /// Marks the resource mapped to the target id as accessed.
    pub(crate) fn mark_accessed(&self, resources: &GpuResources) {
        match &self {
            BindingTarget::Buffer(id) => resources.buffers.mark_accessed(id),
            BindingTarget::Texture(id) => resources.textures.mark_accessed(id),
            BindingTarget::Sampler(id) => resources.samplers.mark_accessed(id),
        }
    }
}

/// Represents gpu resources that can be used in a bind group
pub trait Bindable {
    /// Get the resource binding as it's entire wgpu binding type
    fn as_binding(&self) -> wgpu::BindingType;
    /// Get the id of the target resource the binding refers to
    fn target(&self) -> BindingTarget;
    /// Get the shader stage visibility of the resource binding
    fn visibility(&self) -> wgpu::ShaderStages;
}

/// A resource entry into a bind group
#[derive(Clone, Debug)]
pub struct GroupEntry {
    pub target: BindingTarget,
    pub slot: u32
}

/// A blueprint for constructing wgpu bind groups
#[derive(Clone, Debug)]
pub struct BindGroupBlueprint {
    pub(crate) label: String,
    pub(crate) layout: LayoutBlueprint,
    pub(crate) bindings: Vec<GroupEntry>,
    pub(crate) hold_policy: Option<HoldPolicy>
}

impl BindGroupBlueprint {
    pub fn new() -> Self {
        Self {
            label: "bind_group".to_string(),
            layout: LayoutBlueprint::new(),
            bindings: Vec::new(),
            hold_policy: None,
        }
    }

    /// Set the label for gpu profiling of the resultant bind group
    pub fn with_label(mut self, label: &str) -> Self {
        self.label = label.to_string();
        self
    }

    /// Set the hold policy for this bind group. This overrides the global policy.
    pub fn with_hold_policy(mut self, policy: HoldPolicy) -> Self {
        self.hold_policy = Some(policy);
        self
    }

    /// Add an entry into the bind group
    pub fn with_entry(mut self, entry: impl Bindable) -> Self {
        self.add_entry(entry);
        self
    }

    /// Add an entry into the bind group
    pub fn add_entry(&mut self, entry: impl Bindable) {
        let slot = self.bindings.len() as u32;
        self.layout.add_entry(&entry);

        self.bindings.push(GroupEntry { 
            target: entry.target(),
            slot
        });
    }
}

impl GpuResource for BindGroupBlueprint {
    type Id = BindGroupId;

    fn create_id(&self) -> Self::Id {
        BindGroupId(Uuid::new_v4())
    }
}

/// A blueprint for constucting bind group layouts. This is automatically generated by `BindGroupBlueprint`s.
/// 
/// Ids are generated for one based on it's contents. This ensures that the actual wpgu layout is only created once.
#[derive(Clone, Debug, Hash)]
pub struct LayoutBlueprint {
    pub(crate) entries: Vec<wgpu::BindGroupLayoutEntry>
}

impl LayoutBlueprint {
    pub fn new() -> Self {
        Self { entries: Vec::new() }
    }

    /// Add an entry into the bind group layout
    pub fn with_entry(mut self, entry: &impl Bindable) -> Self {
        self.add_entry(entry);
        self
    }

    /// Add an entry into the bind group layout
    pub fn add_entry(&mut self, entry: &impl Bindable) {
        let slot = self.entries.len() as u32;

        self.entries.push(wgpu::BindGroupLayoutEntry {
            binding: slot,
            visibility: entry.visibility(),
            ty: entry.as_binding(),
            count: None,
        });
    }
}

impl GpuResource for LayoutBlueprint {
    type Id = LayoutId;

    fn create_id(&self) -> Self::Id {
        let mut hasher = DefaultHasher::new();
        self.hash(&mut hasher);
        LayoutId(Uuid::from_u128(hasher.finish() as u128))
    }
}

/// Options for configurating a storage texture binding
/// 
/// Default is `access=WriteOnly` and `format=Rgba16Float`
#[derive(Debug, Clone, Copy)]
pub struct StorageTextureOptions {
    pub access: wgpu::StorageTextureAccess, 
    pub format: wgpu::TextureFormat
}

impl StorageTextureOptions {
    pub fn new(format: wgpu::TextureFormat) -> Self {
        Self {
            access: wgpu::StorageTextureAccess::WriteOnly,
            format
        }
    }

    /// Set the shader access for the texture to read only. 
    /// 
    /// Texture must be annotated with `read` (wgsl) or `read_only` (glsl) in the shader
    pub fn read_only(mut self) -> Self {
        self.access = wgpu::StorageTextureAccess::ReadOnly;
        self
    }

    /// Set the shader access for the texture to read and write. 
    /// 
    /// Texture must be annotated with `read_write` in the shader.
    pub fn read_write(mut self) -> Self {
        self.access = wgpu::StorageTextureAccess::ReadWrite;
        self
    }

    /// Set the shader access for the texture to atomic read write. 
    /// 
    /// Texture must be annotated with `read_write` in the shader.
    pub fn atomic_rw(mut self) -> Self {
        self.access = wgpu::StorageTextureAccess::Atomic;
        self
    }
}

impl Default for StorageTextureOptions {
    fn default() -> Self {
        Self {
            access: wgpu::StorageTextureAccess::WriteOnly,
            format: wgpu::TextureFormat::Rgba16Float
        }
    }
}

/// Options for how a texture is sampled in a shader. 
/// 
/// Default configuration is identical to `SampledTextureOptions::nonfilterable()`
pub struct SampledTextureOptions {
    pub ty: wgpu::TextureSampleType,
    pub multisampled: bool,
}

impl SampledTextureOptions {
    /// The sampled texture is filterable - sampler returns floats.
    pub fn filterable() -> Self {
        Self {
            ty: wgpu::TextureSampleType::Float { filterable: true },
            multisampled: false
        }
    }

    /// The sampled texture is not filterable - sampler returns floats
    pub fn nonfilterable() -> Self {
        Self {
            ty: wgpu::TextureSampleType::Float { filterable: false },
            multisampled: false
        }
    }

    /// Sampler does depth comparisons. Paired sampler must be the `Comparison` type.
    pub fn depth() -> Self {
        Self {
            ty: wgpu::TextureSampleType::Depth,
            multisampled: false
        }
    }

    /// Sampling returns signed integers
    pub fn s_int() -> Self {
        Self {
            ty: wgpu::TextureSampleType::Sint,
            multisampled: false
        }
    }

    /// Sampler returns unsigned integers
    pub fn u_int() -> Self {
        Self {
            ty: wgpu::TextureSampleType::Uint,
            multisampled: false
        }
    }

    /// Allows the texture to sampled multiple times by the shader. 
    /// 
    /// The sample count for the sampled texture must be greater than 1 for this to take effect.
    pub fn with_multisampling(mut self) -> Self {
        self.multisampled = true;
        self
    }
}

impl Default for SampledTextureOptions {
    fn default() -> Self {
        Self {
            ty: wgpu::TextureSampleType::Float { filterable: false },
            multisampled: false
        }
    }
}

/// Represents a texture binding in a bind group
pub struct TextureBinding {
    target: TextureId,
    ty: wgpu::BindingType,
    visibility: wgpu::ShaderStages,
    view_dimensions: wgpu::TextureViewDimension
}

impl TextureBinding {
    pub fn new(target: TextureId, ty: wgpu::BindingType) -> Self {
        Self {
            target,
            ty,
            visibility: wgpu::ShaderStages::FRAGMENT,
            view_dimensions: wgpu::TextureViewDimension::D2
        }
    }

    /// Create a new storage texture binding
    pub fn as_storage(target: TextureId, options: StorageTextureOptions) -> Self {
        let ty = wgpu::BindingType::StorageTexture { 
            access: options.access,
            format: options.format, 
            view_dimension: wgpu::TextureViewDimension::D2
        };

        TextureBinding::new(target, ty)
    }

    /// Create a new sampled texture binding
    pub fn as_sampled(target: TextureId, options: SampledTextureOptions) -> Self {
        let ty = wgpu::BindingType::Texture { 
            sample_type: options.ty, 
            multisampled: options.multisampled,
            view_dimension: wgpu::TextureViewDimension::D2, 
        };

        TextureBinding::new(target, ty)
    }

    /// Set the view dimensions for the texture binding
    pub fn with_view_dimensions(mut self, view_dimensions: wgpu::TextureViewDimension) -> Self {
        self.view_dimensions = view_dimensions;
        self
    }

    /// Set the shader stage visibility for the texture binding
    pub fn with_visibility(mut self, visibility: wgpu::ShaderStages) -> Self {
        self.visibility = visibility;
        self
    }
}

impl Bindable for TextureBinding {
    fn as_binding(&self) -> wgpu::BindingType {
        self.ty
    }

    fn target(&self) -> BindingTarget {
        BindingTarget::Texture(self.target)
    }

    fn visibility(&self) -> wgpu::ShaderStages {
        self.visibility
    }
}

/// Represents a buffer binding and entry in a bind group
pub struct BufferBinding {
    target: BufferId,
    ty: wgpu::BufferBindingType,
    visibility: wgpu::ShaderStages,
    has_dyn_offset: bool,
    min_binding_size: Option<NonZero<u64>>
}

impl BufferBinding {
    pub fn new(target: BufferId, ty: wgpu::BufferBindingType) -> Self {
        Self {
            target,
            ty,
            visibility: wgpu::ShaderStages::VERTEX_FRAGMENT,
            has_dyn_offset: false,
            min_binding_size: None,
        }
    }

    /// Create a new storage buffer binding
    pub fn as_storage(target: BufferId, read_only: bool) -> Self {
        let ty = wgpu::BufferBindingType::Storage { read_only };
        BufferBinding::new(target, ty)
    }

    /// Create a new uniform buffer binding
    pub fn as_uniform(target: BufferId) -> Self {
        let ty = wgpu::BufferBindingType::Uniform;
        BufferBinding::new(target, ty)
    }

    /// Set the shader stage visibility for the buffer binding
    pub fn with_visibility(mut self, visibility: wgpu::ShaderStages) -> Self {
        self.visibility = visibility;
        self
    }

    /// Set the binding to have a dynamic offset
    pub fn with_dynamic_offset(mut self) -> Self {
        self.has_dyn_offset = true;
        self
    }

    /// Set the minimum buffer size for the binding. Must be greater than 0.
    pub fn with_min_size(mut self, size: u64) -> Self {
        self.min_binding_size = Some(NonZero::new(size)
            .expect("[Buffer Binding] Expected minimum binding size to be a non zero unsigned number."));
        self
    }
}

impl Bindable for BufferBinding {
    fn as_binding(&self) -> wgpu::BindingType {
        wgpu::BindingType::Buffer {
            ty: self.ty,
            has_dynamic_offset: self.has_dyn_offset,
            min_binding_size: self.min_binding_size
        }
    }

    fn target(&self) -> BindingTarget {
        BindingTarget::Buffer(self.target)
    }

    fn visibility(&self) -> wgpu::ShaderStages {
        self.visibility
    }
}


/// Represents the binding of a Sampler in a bind group
pub struct SamplerBinding {
    target: SamplerId,
    visibility: wgpu::ShaderStages,
    ty: wgpu::SamplerBindingType,
}

impl SamplerBinding {
    /// Sampler result is produced from more than one color sample.
    pub fn filtering(target: SamplerId) -> Self {
        Self {
            target,
            ty: wgpu::SamplerBindingType::Filtering,
            visibility: wgpu::ShaderStages::VERTEX_FRAGMENT,
        }
    }

    /// Sampler result is produced from just one color sample.
    pub fn non_filtering(target: SamplerId) -> Self {
        Self {
            target,
            ty: wgpu::SamplerBindingType::NonFiltering,
            visibility: wgpu::ShaderStages::VERTEX_FRAGMENT,
        }
    }

    /// Sampler result is produced from comparing color samples, based on the sampler compare function.
    pub fn comparison(target: SamplerId) -> Self {
        Self {
            target,
            ty: wgpu::SamplerBindingType::Comparison,
            visibility: wgpu::ShaderStages::VERTEX_FRAGMENT,
        }
    }

    /// Set the shader stage visibility for the sampler binding
    pub fn with_visibility(mut self, visibility: wgpu::ShaderStages) -> Self {
        self.visibility = visibility;
        self
    }

    /// Set the binding type of the sampler binding
    pub fn with_binding_type(mut self, ty: wgpu::SamplerBindingType) -> Self{
        self.ty = ty;
        self
    }
}

impl Bindable for SamplerBinding {
    fn as_binding(&self) -> wgpu::BindingType {
        wgpu::BindingType::Sampler(self.ty)
    }

    fn target(&self) -> super::BindingTarget {
        BindingTarget::Sampler(self.target)
    }

    fn visibility(&self) -> wgpu::ShaderStages {
        self.visibility
    }
}